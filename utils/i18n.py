def tr(key: str) -> str:
    """Devuelve el texto traducido para `key` en el idioma activo."""
    lang_dict = STRINGS.get(CURRENT_LANGUAGE, STRINGS["en"])
    return lang_dict.get(key, STRINGS["en"].get(key, key))


def set_language(lang: str):
    """Cambia el idioma activo si existe en STRINGS."""
    global CURRENT_LANGUAGE
    if lang in STRINGS:
        CURRENT_LANGUAGE = lang


def available_languages() -> list:
    return list(STRINGS.keys())
